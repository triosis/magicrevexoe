CREATE TABLE billable_usage (
id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
tenant_id BIGINT UNSIGNED NOT NULL,
subscription_id BIGINT UNSIGNED NOT NULL,
branch_id BIGINT UNSIGNED NOT NULL,
short_link_id BIGINT UNSIGNED NOT NULL,
metric ENUM('scan','ai_draft') NOT NULL,
request_key BINARY(16) NOT NULL,
form_digest BINARY(32) NOT NULL,
input_sha256 BINARY(32) NOT NULL,
language ENUM('en','hi','ml') NOT NULL,
status ENUM('reserved','complete','failed','unknown') NOT NULL,
reserved_tokens BIGINT UNSIGNED NOT NULL,
input_tokens BIGINT UNSIGNED NULL,
output_tokens BIGINT UNSIGNED NULL,
draft_text TEXT NULL,
expires_at DATETIME(6) NOT NULL,
created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
UNIQUE KEY uq_billable_request (tenant_id,metric,request_key),
KEY ix_billable_period (tenant_id,subscription_id,metric,status,id),
CONSTRAINT fk_billable_subscription FOREIGN KEY (tenant_id,subscription_id) REFERENCES subscriptions(tenant_id,id),
CONSTRAINT fk_billable_link FOREIGN KEY (tenant_id,branch_id,short_link_id) REFERENCES short_links(tenant_id,branch_id,id),
CONSTRAINT ck_billable_result CHECK ((metric='scan' AND status='complete' AND draft_text IS NULL AND reserved_tokens=0) OR (metric='ai_draft' AND reserved_tokens>0 AND (status<>'complete' OR (draft_text IS NOT NULL AND input_tokens IS NOT NULL AND output_tokens IS NOT NULL))))
) ENGINE=InnoDB DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci
