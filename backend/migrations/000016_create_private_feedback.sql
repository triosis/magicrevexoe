CREATE TABLE private_feedback (
id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
public_id BINARY(16) NOT NULL,
tenant_id BIGINT UNSIGNED NOT NULL,
branch_id BIGINT UNSIGNED NOT NULL,
funnel_configuration_id BIGINT UNSIGNED NOT NULL,
industry_channel_id BIGINT UNSIGNED NOT NULL,
short_link_id BIGINT UNSIGNED NOT NULL,
submission_key_hash BINARY(32) NOT NULL,
overall_rating TINYINT UNSIGNED NOT NULL,
service_rating TINYINT UNSIGNED NULL,
cleanliness_rating TINYINT UNSIGNED NULL,
waiting_time_rating TINYINT UNSIGNED NULL,
status ENUM('new','in_progress','resolved','dismissed') NOT NULL DEFAULT 'new',
assigned_membership_id BIGINT UNSIGNED NULL,
lock_version INT UNSIGNED NOT NULL DEFAULT 1,
submitted_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
resolved_at DATETIME(6) NULL,
UNIQUE KEY uq_feedback_public (public_id),
UNIQUE KEY uq_feedback_submission (tenant_id,submission_key_hash),
UNIQUE KEY uq_feedback_owner (tenant_id,id),
KEY ix_feedback_status (tenant_id,branch_id,status,submitted_at,id),
KEY ix_feedback_assignee (tenant_id,assigned_membership_id,status,submitted_at,id),
CONSTRAINT fk_feedback_funnel FOREIGN KEY (tenant_id,branch_id,funnel_configuration_id,industry_channel_id) REFERENCES funnel_configurations(tenant_id,branch_id,id,industry_channel_id),
CONSTRAINT fk_feedback_short FOREIGN KEY (tenant_id,branch_id,short_link_id) REFERENCES short_links(tenant_id,branch_id,id),
CONSTRAINT fk_feedback_assignee FOREIGN KEY (tenant_id,assigned_membership_id) REFERENCES tenant_memberships(tenant_id,id),
CONSTRAINT ck_feedback_ratings CHECK (overall_rating BETWEEN 1 AND 5 AND (service_rating IS NULL OR service_rating BETWEEN 1 AND 5) AND (cleanliness_rating IS NULL OR cleanliness_rating BETWEEN 1 AND 5) AND (waiting_time_rating IS NULL OR waiting_time_rating BETWEEN 1 AND 5)),
CONSTRAINT ck_feedback_resolved CHECK ((status='resolved' AND resolved_at IS NOT NULL) OR (status<>'resolved' AND resolved_at IS NULL)),
created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6)
) ENGINE=InnoDB DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci
