CREATE TABLE subscriptions (
id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
tenant_id BIGINT UNSIGNED NOT NULL,
tenant_kind ENUM('platform','reseller','sub_reseller','merchant') NOT NULL DEFAULT 'merchant',
plan_id BIGINT UNSIGNED NOT NULL,
status ENUM('trialing','active','past_due','canceled','expired') NOT NULL,
starts_at DATETIME(6) NOT NULL,
ends_at DATETIME(6) NULL,
current_period_start DATETIME(6) NOT NULL,
current_period_end DATETIME(6) NOT NULL,
cancel_at_period_end BOOLEAN NOT NULL DEFAULT 0,
current_slot TINYINT GENERATED ALWAYS AS (CASE WHEN status IN ('trialing','active','past_due') THEN 1 ELSE NULL END) PERSISTENT,
lock_version INT UNSIGNED NOT NULL DEFAULT 1,
UNIQUE KEY uq_subscription_owner (tenant_id,id),
UNIQUE KEY uq_subscription_current (tenant_id,current_slot),
KEY ix_subscription_history (tenant_id,created_at,id),
KEY ix_subscription_period (status,current_period_end),
CONSTRAINT fk_subscription_tenant FOREIGN KEY (tenant_id,tenant_kind) REFERENCES tenants(id,kind),
CONSTRAINT fk_subscription_plan FOREIGN KEY (plan_id) REFERENCES subscription_plans(id),
CONSTRAINT ck_subscription_merchant CHECK (tenant_kind='merchant'),
CONSTRAINT ck_subscription_period CHECK (current_period_end>current_period_start AND (ends_at IS NULL OR ends_at>=starts_at)),
CONSTRAINT ck_subscription_cancel CHECK (cancel_at_period_end IN (0,1)),
created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6)
) ENGINE=InnoDB DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci
