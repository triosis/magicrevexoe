CREATE TABLE audit_logs (
id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
event_id BINARY(16) NOT NULL,
tenant_id BIGINT UNSIGNED NOT NULL,
actor_user_id BIGINT UNSIGNED NULL,
actor_membership_id BIGINT UNSIGNED NULL,
actor_tenant_id BIGINT UNSIGNED NULL,
action VARCHAR(96) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
resource_type VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
resource_id BIGINT UNSIGNED NULL,
request_id BINARY(16) NOT NULL,
outcome ENUM('success','denied') NOT NULL,
safe_metadata JSON NOT NULL,
occurred_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
UNIQUE KEY uq_audit_event (event_id),
KEY ix_audit_tenant (tenant_id,occurred_at,id),
KEY ix_audit_resource (tenant_id,resource_type,resource_id,occurred_at,id),
KEY ix_audit_actor (actor_user_id,occurred_at,id),
KEY ix_audit_request (request_id),
CONSTRAINT fk_audit_tenant FOREIGN KEY (tenant_id) REFERENCES tenants(id),
CONSTRAINT fk_audit_user FOREIGN KEY (actor_user_id) REFERENCES users(id),
CONSTRAINT fk_audit_membership FOREIGN KEY (actor_tenant_id,actor_membership_id,actor_user_id) REFERENCES tenant_memberships(tenant_id,id,user_id),
CONSTRAINT ck_audit_actor CHECK ((actor_membership_id IS NULL AND actor_tenant_id IS NULL) OR (actor_membership_id IS NOT NULL AND actor_tenant_id IS NOT NULL AND actor_user_id IS NOT NULL)),
CONSTRAINT ck_audit_metadata CHECK (JSON_TYPE(safe_metadata)='OBJECT'),
created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6)
) ENGINE=InnoDB DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci
