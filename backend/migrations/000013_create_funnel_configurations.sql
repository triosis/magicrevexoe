CREATE TABLE funnel_configurations (
id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
tenant_id BIGINT UNSIGNED NOT NULL,
branch_id BIGINT UNSIGNED NOT NULL,
industry_channel_id BIGINT UNSIGNED NOT NULL,
channel_version_id BIGINT UNSIGNED NOT NULL,
review_destination_id BIGINT UNSIGNED NOT NULL,
revision INT UNSIGNED NOT NULL,
status ENUM('draft','published','retired') NOT NULL DEFAULT 'draft',
brand_title VARCHAR(120) NOT NULL,
accent_hex CHAR(7) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
locale VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
published_at DATETIME(6) NULL,
UNIQUE KEY uq_funnel_revision (tenant_id,branch_id,revision),
UNIQUE KEY uq_funnel_owner (tenant_id,branch_id,id),
UNIQUE KEY uq_funnel_channel (tenant_id,branch_id,id,industry_channel_id),
KEY ix_funnel_status (tenant_id,status,id),
CONSTRAINT fk_funnel_branch FOREIGN KEY (tenant_id,branch_id,industry_channel_id) REFERENCES branches(tenant_id,id,industry_channel_id),
CONSTRAINT fk_funnel_version FOREIGN KEY (industry_channel_id,channel_version_id) REFERENCES channel_versions(industry_channel_id,id),
CONSTRAINT fk_funnel_destination FOREIGN KEY (tenant_id,branch_id,review_destination_id) REFERENCES review_destinations(tenant_id,branch_id,id),
CONSTRAINT ck_funnel_revision CHECK (revision>0),
CONSTRAINT ck_funnel_color CHECK (accent_hex REGEXP '^#[0-9A-Fa-f]{6}$'),
CONSTRAINT ck_funnel_publish CHECK ((status='draft' AND published_at IS NULL) OR (status IN ('published','retired') AND published_at IS NOT NULL)),
created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6)
) ENGINE=InnoDB DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci
