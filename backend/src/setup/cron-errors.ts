import {MigrationError} from '../migrations/runner.js'
import {ZodError} from 'zod'

const safeCodes=new Set([
 'INVALID_ARGUMENTS','INITIALIZATION_CONFIRMATION_REQUIRED','INITIALIZATION_RELEASE_MISMATCH',
 'INITIALIZATION_REFERENCE_MISMATCH','INITIALIZATION_MANIFEST_OR_RELEASE_MISMATCH',
 'INITIALIZATION_MANIFEST_MISMATCH','INITIALIZATION_ALREADY_ATTEMPTED_REVIEW_REQUIRED',
 'INITIALIZATION_PREFLIGHT_REQUIRED','INITIALIZATION_INTERRUPTED','INITIALIZATION_UNAPPROVED_DEFINER',
 'INITIALIZATION_LOCK_UNAVAILABLE','INITIALIZATION_LOCK_LOST','INITIALIZATION_STATE_SCHEMA_DRIFT',
 'SEPARATE_INITIALIZATION_STATE_DATABASE_REQUIRED','MISSING_INITIALIZATION_CREDENTIALS',
 'HOSTINGER_WILDCARD_APPROVAL_REQUIRED','HOSTINGER_WILDCARD_APPROVAL_EXPIRED_OR_NOT_ACTIVE',
 'HOSTINGER_WILDCARD_APPROVAL_EXPIRED','HOSTINGER_WILDCARD_PHASE_MISMATCH',
 'HOSTINGER_LOCAL_APPROVAL_MISMATCH','INVALID_HOSTINGER_LOCAL_TRANSPORT_OR_APPROVAL',
 'UNEXPECTED_DATABASE_TARGET','UNSUPPORTED_DATABASE_VERSION','HOSTINGER_WILDCARD_GRANT_DRIFT',
 'HOSTINGER_WILDCARD_IDENTITY_VERSION_OR_ROLE','HOSTINGER_WILDCARD_PRIVILEGE_SET_MISMATCH',
 'PREFLIGHT_APPROVAL_MISMATCH','EXPLICIT_RECENT_APPROVAL_REQUIRED','SCHEMA_DRIFT_REQUIRES_REVIEW',
 'MIGRATION_LOCK_UNAVAILABLE','MIGRATION_OPERATION_FAILED',
])
const drivers=new Set(['ER_ACCESS_DENIED_ERROR','ER_DBACCESS_DENIED_ERROR','ER_BAD_DB_ERROR','ECONNREFUSED','ETIMEDOUT','ENOTFOUND','ER_DUP_ENTRY'])
export function cronErrorCode(error:unknown):string{
 if(error instanceof ZodError)return 'INVALID_INITIALIZATION_CONFIGURATION'
 if(error instanceof SyntaxError)return 'INVALID_INITIALIZATION_JSON'
 if(error instanceof Error&&safeCodes.has(error.message))return error.message
 if(error instanceof MigrationError&&safeCodes.has(error.code))return error.code
 if(error&&typeof error==='object'&&'code' in error&&typeof error.code==='string'&&drivers.has(error.code))return error.code
 return 'INITIALIZATION_UNKNOWN_FAILURE'
}
